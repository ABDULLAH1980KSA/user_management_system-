#!/bin/bash
# =====================================================
# run.sh – سكريبت تشغيل مدرسة الشقيق الابتدائية
# الاستخدام:  bash run.sh
#             bash run.sh 0.0.0.0:8000
# =====================================================

set -e

# المنفذ الافتراضي
PORT="${1:-0.0.0.0:8000}"

echo "========================================"
echo "  مدرسة الشقيق الابتدائية بنين"
echo "  نظام إدارة الأسئلة الإلكترونية"
echo "========================================"

# 1. التحقق من Python
if ! command -v python3 &>/dev/null; then
    echo "[خطأ] Python3 غير مثبّت. ثبّته أولاً."
    exit 1
fi
echo "[✔] Python: $(python3 --version)"

# 2. تثبيت المتطلبات
echo ""
echo "[...] تثبيت المتطلبات..."
pip3 install -r requirements.txt --quiet
echo "[✔] تم تثبيت المتطلبات"

# 3. تطبيق الـ migrations
echo ""
echo "[...] تطبيق تحديثات قاعدة البيانات..."
python3 manage.py migrate --run-syncdb
echo "[✔] قاعدة البيانات جاهزة"

# 4. جمع الملفات الثابتة (اختياري – للبيئة الإنتاجية)
# python3 manage.py collectstatic --noinput

# 5. تشغيل السيرفر
echo ""
echo "========================================"
echo "  السيرفر يعمل على: http://$PORT"
echo "  اضغط Ctrl+C للإيقاف"
echo "========================================"
echo ""

python3 manage.py runserver "$PORT"
